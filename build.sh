#!/usr/bin/env bash
# ============================================================
#  build.sh —— macOS / Linux 一键构建并运行
#  依赖：CMake + C++ 编译器（macOS：Xcode Command Line Tools）。
#  SFML 已随仓库自带（SFML-3.1.0/）→ 静态编译进程序，不联网、不下载。
# ============================================================
set -e
cd "$(dirname "$0")"          # 切到脚本所在目录（= 项目根，保证贴图/字体相对路径能找到）

cmake -S . -B build          # 首次会用自带的 SFML 源码静态编译，约几分钟，仅一次
cmake --build build

./ark                        # 运行（可执行文件生成在项目根目录）
