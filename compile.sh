#!/usr/bin/env bash
# ============================================================
#  compile.sh —— macOS / Linux 快速重新编译并运行（不重新配置）
#  用途：改完 main.cpp 后想快速看效果时用它。它只做增量编译，
#        【跳过 cmake 配置】，所以必须先成功执行过一次 build.sh。
#  （对应 Windows 上的 compile.bat）
# ============================================================
set -e
cd "$(dirname "$0")"          # 切到脚本所在目录（= 项目根，保证贴图/字体相对路径能找到）

cmake --build build          # 只增量编译（SFML 已编译过，通常几秒）

./ark                        # 运行（可执行文件生成在项目根目录）
